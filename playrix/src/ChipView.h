#pragma once

#include "Config.h"

namespace m3 {

// Визуальное состояние одной фишки — всё, чем картинка отличается от
// логического поля. Board знает только цвет в клетке; смещение и прозрачность
// живут здесь, поэтому логика остаётся мгновенной, а анимация — поверх неё.
struct ChipView {
    // Сдвиг по горизонтали от «родной» клетки, в пикселях. Нужен только
    // перетасовке: при падении фишки не меняют столбец, и он остаётся нулём.
    float offsetX = 0.0f;

    // Сдвиг по вертикали от «родной» клетки, в пикселях.
    // Отрицательный — фишка ещё не доехала и висит выше; 0 — на месте.
    float offsetY = 0.0f;

    // Текущая скорость падения, px/s. Разгоняется гравитацией.
    float speed = 0.0f;

    // 1 — фишка видна полностью, 0 — растворилась без остатка.
    float alpha = 1.0f;
};

// Летящий спрайт бустера поверх поля — самолётик, летящий к своей цели, или
// одна из пары ракет, летящих к краю поля. Живёт только во время короткой
// фазы Phase::Boosting перед обычным затуханием снесённых клеток; from/to —
// координаты клеток (не пиксели), Renderer сам считает текущее положение по
// прогрессу полёта.
struct BoosterFlight {
    cfg::BoosterType type    = cfg::BoosterType::None;
    float            fromRow = 0.0f;
    float            fromCol = 0.0f;
    float            toRow   = 0.0f;
    float            toCol   = 0.0f;
};

}  // namespace m3
