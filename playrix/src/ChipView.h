#pragma once

namespace m3 {

// Визуальное состояние одной фишки — всё, чем картинка отличается от
// логического поля. Board знает только цвет в клетке; смещение и прозрачность
// живут здесь, поэтому логика остаётся мгновенной, а анимация — поверх неё.
struct ChipView {
    // Сдвиг по вертикали от «родной» клетки, в пикселях.
    // Отрицательный — фишка ещё не доехала и висит выше; 0 — на месте.
    float offsetY = 0.0f;

    // Текущая скорость падения, px/s. Разгоняется гравитацией.
    float speed = 0.0f;

    // 1 — фишка видна полностью, 0 — растворилась без остатка.
    float alpha = 1.0f;
};

}  // namespace m3
